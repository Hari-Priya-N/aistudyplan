"""
Deterministic, keyless mock provider.

Useful for local development, CI, and automated tests where hitting a real
LLM (cost, latency, network) isn't desirable. It implements the exact same
LLMProvider interface as Grok/OpenAI/Ollama, so every tool, the RAG engine,
and the LangGraph agent work unmodified against it — only LLM_PROVIDER=mock
changes.

It does simple, rule-based text generation instead of real reasoning, so
outputs are structurally valid (correct JSON shape when json_mode=True) but
not "smart". Good enough to exercise every code path end-to-end.
"""
import hashlib
import json
import re

from app.llm.base import LLMProvider
from app.llm.local_embeddings import embed_texts


def _last_user_content(messages: list[dict]) -> str:
    for m in reversed(messages):
        if m.get("role") == "user":
            return m.get("content", "")
    return messages[-1].get("content", "") if messages else ""


class MockProvider(LLMProvider):
    def __init__(self, model: str = "mock-1"):
        self.model = model

    def complete(
        self,
        messages: list[dict],
        *,
        temperature: float = 0.3,
        max_tokens: int = 1500,
        json_mode: bool = False,
    ) -> str:
        system = " ".join(m["content"] for m in messages if m.get("role") == "system")
        user = _last_user_content(messages)

        if json_mode:
            return self._json_response(system, user)

        return (
            f"[mock-llm response] Based on: \"{user[:160].strip()}\" — "
            "this is a deterministic placeholder answer generated by the "
            "mock provider (set LLM_PROVIDER=grok/openai/ollama for real output)."
        )

    def embed(self, texts: list[str]) -> list[list[float]]:
        return embed_texts(texts)

    # -- internal: shape-correct JSON for each known prompt family ----------
    def _json_response(self, system: str, user: str) -> str:
        sys_l = system.lower()
        usr_l = user.lower()

        if "knowledge graph" in sys_l or "topic" in sys_l and "sub-topic" in sys_l:
            return json.dumps(self._fake_topic_tree(user))
        if "flashcard" in sys_l or "study kit" in sys_l:
            return json.dumps(self._fake_study_kit(user))
        if "quiz" in sys_l and "question" in sys_l:
            return json.dumps(self._fake_quiz(user))
        if "explain" in sys_l and "incorrect" in sys_l:
            return json.dumps(
                {"explanation": "This option is incorrect because it misapplies the "
                                 "core concept being tested; review the topic notes "
                                 "and retry a similar question."}
            )
        if "study plan" in sys_l or "planner" in sys_l:
            return json.dumps(self._fake_study_plan(user))
        if "remediation" in sys_l or "micro-learning" in sys_l:
            return json.dumps(
                {
                    "title": "Targeted Review",
                    "explanation": "A focused recap of the sub-concept you missed, "
                                    "broken into a short walkthrough and one practice item.",
                    "practice_question": "Quick check: can you restate the concept in your own words?",
                }
            )

        # generic fallback: echo a minimal valid object
        return json.dumps({"result": f"mock output for: {user[:120]}"})

    def _topic_seed(self, text: str) -> list[str]:
        # Prefer values of "title"/"description" keys when the source looks
        # like JSON (our sample syllabus format) — much cleaner than generic
        # word-scraping, which would otherwise pick up JSON keys like
        # "topics" or "title" themselves as fake topics.
        json_values = re.findall(r'"(?:title|description|course)"\s*:\s*"([^"]{4,80})"', text)
        if json_values:
            seen, out = set(), []
            for v in json_values:
                key = v.lower()
                if key not in seen:
                    seen.add(key)
                    out.append(v.strip())
                if len(out) >= 6:
                    break
            return out

        words = re.findall(r"[A-Za-z][A-Za-z\- ]{3,40}", text)
        candidates = [w.strip() for w in words if len(w.strip()) > 4]
        seen, out = set(), []
        for c in candidates:
            key = c.lower()
            if key not in seen:
                seen.add(key)
                out.append(c)
            if len(out) >= 5:
                break
        if not out:
            out = ["Foundations", "Core Concepts", "Applications"]
        return out

    def _fake_topic_tree(self, user: str) -> dict:
        topics = self._topic_seed(user)
        return {
            "topics": [
                {
                    "title": t,
                    "difficulty": ["easy", "medium", "hard"][i % 3],
                    "subtopics": [
                        {"title": f"{t} — fundamentals", "difficulty": "easy"},
                        {"title": f"{t} — practice", "difficulty": "medium"},
                    ],
                }
                for i, t in enumerate(topics)
            ]
        }

    def _fake_quiz(self, user: str) -> dict:
        digest = hashlib.sha1(user.encode()).hexdigest()[:6]
        return {
            "questions": [
                {
                    "question": f"Sample question {i + 1} on the given topic ({digest})?",
                    "options": ["Option A", "Option B", "Option C", "Option D"],
                    "correct_index": i % 4,
                    "difficulty": "medium",
                }
                for i in range(5)
            ]
        }

    def _fake_study_kit(self, user: str) -> dict:
        return {
            "summary": f"A concise summary covering the key points of: {user[:100].strip()}",
            "flashcards": [
                {"front": f"Key term {i + 1}", "back": f"Definition {i + 1}"}
                for i in range(5)
            ],
            "quiz": self._fake_quiz(user)["questions"],
            "step_by_step_guide": [
                "Identify what is being asked.",
                "Recall the relevant rule or formula.",
                "Apply it step by step.",
                "Sanity-check the result.",
            ],
        }

    def _fake_study_plan(self, user: str) -> dict:
        topics = self._topic_seed(user)
        return {
            "ordered_topics": [
                {"title": t, "reason": "Builds on prerequisite mastery", "order": i + 1}
                for i, t in enumerate(topics)
            ]
        }
